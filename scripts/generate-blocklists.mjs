import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const sourcePath = path.join(root, 'src/data/ai-services.json')
const outputDir = path.join(root, 'rules/generated')

const rulePack = JSON.parse(await readFile(sourcePath, 'utf8'))

const domains = Array.from(
  new Set(
    rulePack.categories.flatMap((category) =>
      category.services.flatMap((service) => (service.strictOnly ? [] : service.domains)),
    ),
  ),
).sort((a, b) => a.localeCompare(b))

const header = (name) =>
  [
    `# Aegis AI Blocker - ${name}`,
    `# Rule pack: ${rulePack.version}`,
    `# Updated: ${rulePack.updatedAt}`,
    `# ${rulePack.disclaimer}`,
    '',
  ].join('\n')

await mkdir(outputDir, { recursive: true })

await writeFile(
  path.join(outputDir, 'adguard.txt'),
  `${header('AdGuard/uBlock DNS filters')}${domains.map((domain) => `||${domain}^`).join('\n')}\n`,
)

await writeFile(
  path.join(outputDir, 'hosts.txt'),
  `${header('Hosts file')}${domains
    .map((domain) => [`0.0.0.0 ${domain}`, `:: ${domain}`].join('\n'))
    .join('\n')}\n`,
)

await writeFile(
  path.join(outputDir, 'dnsmasq.conf'),
  `${header('dnsmasq')}${domains.map((domain) => `address=/${domain}/0.0.0.0`).join('\n')}\n`,
)

await writeFile(path.join(outputDir, 'domains.txt'), `${header('Plain domains')}${domains.join('\n')}\n`)

// The iOS app consumes the same rule pack via a generated Swift file so the
// two platforms can never drift apart.
const sfSymbols = {
  chat: 'sparkles',
  search: 'magnifyingglass',
  coding: 'curlybraces',
  creative: 'wand.and.stars',
  api: 'globe',
}

const swiftString = (value) => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

const swiftCategories = rulePack.categories
  .map((category) => {
    const services = category.services
      .map((service) => {
        const domains = service.domains.map(swiftString).join(', ')
        const strict = service.strictOnly ? ', strictOnly: true' : ''
        return `                RuleService(name: ${swiftString(service.name)}, domains: [${domains}]${strict})`
      })
      .join(',\n')

    return [
      '        RuleCategory(',
      `            id: ${swiftString(category.id)},`,
      `            name: ${swiftString(category.name)},`,
      `            symbol: ${swiftString(sfSymbols[category.id] ?? 'shield')},`,
      `            colorHex: 0x${category.color.slice(1)},`,
      '            services: [',
      services,
      '            ]',
      '        )',
    ].join('\n')
  })
  .join(',\n')

const swiftFile = `// Generated by scripts/generate-blocklists.mjs — do not edit by hand.
// Source of truth: src/data/ai-services.json

enum RulePackData {
    static let version = ${swiftString(rulePack.version)}
    static let updatedAt = ${swiftString(rulePack.updatedAt)}

    static let categories: [RuleCategory] = [
${swiftCategories}
    ]
}
`

await writeFile(path.join(root, 'ios/AegisAIBlocker/RulePackData.generated.swift'), swiftFile)

// The browser extension (extension/) enforces the policy live via
// declarativeNetRequest. It bundles a flattened copy of the pack — services
// with their category + the policy modes — so its enforcement always matches
// this rule pack. Generated, never hand-edited.
const extensionPack = {
  generated: 'scripts/generate-blocklists.mjs — do not edit by hand',
  version: rulePack.version,
  updatedAt: rulePack.updatedAt,
  disclaimer: rulePack.disclaimer,
  policies: rulePack.policies,
  services: rulePack.categories.flatMap((category) =>
    category.services.map((service) => ({
      name: service.name,
      category: category.id,
      domains: service.domains,
      strictOnly: Boolean(service.strictOnly),
    })),
  ),
}

const extensionRulesDir = path.join(root, 'extension/rules')
await mkdir(extensionRulesDir, { recursive: true })
await writeFile(path.join(extensionRulesDir, 'pack.json'), `${JSON.stringify(extensionPack, null, 2)}\n`)

console.log(
  `Generated ${domains.length} default domains in ${path.relative(root, outputDir)}, ` +
    `RulePackData.generated.swift, and extension/rules/pack.json (${extensionPack.services.length} services)`,
)
